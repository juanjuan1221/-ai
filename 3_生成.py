r"""
============================================================
  3_生成.py —— 用训练好的模型生成新结构
============================================================
运行：PyCharm 右键 → 运行。会读取 存档/最新.pt，
      生成 配置.生成数量 个结构到 输出/待放置/ 文件夹。
然后进游戏，拿着【AI生成器】左键挥动：
      每挥一次放置一个（放在你面前），放过的文件会被挪到 输出/已放置/
      按住 Shift 挥动 = 撤销上一次放置

也可以命令行指定数量和标签：
      python 3_生成.py 8 房子
"""
import 自动切换GPU
自动切换GPU.确保GPU()

import sys
import time

import torch

import 配置
import 数据集
import 存档
from 扩散 import 采样


def main():
    配置.检查配置()
    设备 = "cuda" if torch.cuda.is_available() else "cpu"
    档, _, EMA模型 = 存档.读取(存档.最新存档, 设备)
    if 档 is None:
        print(f"没有找到存档 {存档.最新存档}，请先运行 2_训练.py")
        return
    EMA模型.eval()
    词表, 标签表, 尺寸 = 档["词表"], 档["标签表"], tuple(档["结构尺寸"])
    print(f"模型：已训练 {档['轮数']} 轮，尺寸 {尺寸}，词表 {len(词表)}，可用标签 {标签表}")

    数量 = int(sys.argv[1]) if len(sys.argv) > 1 else 配置.生成数量
    标签 = sys.argv[2] if len(sys.argv) > 2 else 配置.默认生成标签
    标签编号 = None
    if 标签 is not None:
        if 标签 not in 标签表:
            print(f"✗ 标签「{标签}」不存在，可用的有：{标签表}")
            return
        标签编号 = 标签表.index(标签)
    print(f"生成 {数量} 个，标签={标签 or '不指定'}，步数={配置.生成步数}，温度={配置.生成温度}，引导={配置.引导强度}")

    时间戳 = time.strftime("%Y%m%d_%H%M%S")
    已生成 = 0
    while 已生成 < 数量:
        本批 = min(配置.生成批大小, 数量 - 已生成)
        print(f"  第 {已生成 + 1}~{已生成 + 本批} 个：")
        结果 = 采样(EMA模型, 本批, 尺寸, 标签编号, 配置.生成步数, 配置.生成温度, 配置.引导强度,
                  配置.揭示随机性, 设备, 配置.使用混合精度)
        for i in range(本批):
            路径 = 配置.待放置目录 / f"生成_{时间戳}_{已生成 + 1:03d}.json"
            n = 数据集.保存结构(结果[i], 词表, 路径, 标签 or "默认")
            print(f"  ✔ {路径.name}  非空气方块 {n} 个")
            已生成 += 1
    print(f"\n完成！文件在 {配置.待放置目录}")
    print("进游戏拿 AI生成器 挥动即可放置（Shift+挥动 = 撤销）。")


if __name__ == "__main__":
    main()
