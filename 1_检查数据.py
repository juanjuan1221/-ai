from collections import Counter

import 配置
import 数据集

配置.检查配置()
print("=" * 60)
print(f"数据目录：{配置.数据目录}")
print(f"配置的结构尺寸：{配置.结构尺寸}    保留方块状态：{配置.保留方块状态}    旋转增强：{配置.旋转增强}")
print("=" * 60)

样本们 = 数据集.读取全部样本()
if not 样本们:
    print("\n还没有任何有效样本！")
    print("请进游戏，拿着【采样器】站在建筑中间（脚下是地板），左键挥动一下即可采集。")
    print("按住 Shift 再挥动 = 只显示采集范围（粒子框），不采集。")
    raise SystemExit

标签计数 = Counter(s["标签"] for s in 样本们)
print("\n【标签统计】")
for 名, n in 标签计数.most_common():
    print(f"  {名:<12} {n} 个")

方块计数 = Counter()
for s in 样本们:
    编号计数 = s["网格"].flatten().bincount(minlength=len(s["调色板"]))
    for i, n in enumerate(编号计数.tolist()):
        if n:
            方块计数[s["调色板"][i]] += n

总格子 = sum(方块计数.values())
print(f"\n【方块统计】共 {len(方块计数)} 种方块状态")
for 名, n in 方块计数.most_common(20):
    print(f"  {n / 总格子 * 100:6.2f}%  {名}")

词表 = 数据集.构建词表(样本们)
print(f"\n算上旋转后，词表大小 = {len(词表)}")
训练项数 = len(样本们) * len(数据集.可用旋转次数())
print(f"训练项数（含旋转）= {训练项数}")

print("\n【样本详情】")
for s in 样本们:
    非空气 = int((s["网格"] != 0).sum())
    print(f"  {s['文件']:<36} 标签={s['标签']:<8} 非空气方块={非空气:>6}  方块种类={len(s['调色板'])}")

print("\n【建议】")
空气占比 = 方块计数.get(数据集.空气, 0) / 总格子
if len(样本们) < 20:
    print(f"  · 样本只有 {len(样本们)} 个，建议至少 30~50 个同类建筑，越多越好。少于 20 个模型基本只会背答案。")
if 空气占比 > 0.9:
    print(f"  · 空气占了 {空气占比 * 100:.1f}%，建筑相对采集框太小。可以把 Java 和 配置.py 的尺寸调小，或采集更大的建筑。")
for 名, n in 标签计数.items():
    if n < 10:
        print(f"  · 标签「{名}」只有 {n} 个样本，太少了。")
if len(方块计数) > 400:
    print(f"  · 方块种类 {len(方块计数)} 很多，数据少时可以把 配置.保留方块状态 改成 False 试试。")
print("  · 检查完没问题就可以运行 2_训练.py 了。")
